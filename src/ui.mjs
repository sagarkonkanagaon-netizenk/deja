import { openDb } from './db.mjs';
import { projectName } from './util.mjs';
import { VERSION } from './version.mjs';

const LIMIT = 5000;

export function collect(project) {
  const db = openDb();
  const scope = project ? 'WHERE project = ?' : '';
  const args = project ? [project] : [];
  const anchors = db.prepare('SELECT path FROM anchors WHERE memory_id = ?');
  const memories = db.prepare(`SELECT id, project, kind, title, body, tags, stale, hits, created_at, updated_at, session_id
    FROM memories ${scope} ORDER BY updated_at DESC LIMIT ${LIMIT}`).all(...args)
    .map((m) => ({ ...m, files: anchors.all(m.id).map((a) => a.path) }));
  const projects = [...new Set([
    ...memories.map((m) => m.project),
    ...db.prepare(`SELECT DISTINCT project FROM sessions ${scope}`).all(...args).map((r) => r.project),
  ])].map((key) => ({ key, name: projectName(key) }));
  return {
    version: VERSION,
    generatedAt: Date.now(),
    scope: project ? 'project' : 'all',
    projects,
    memories,
    commands: db.prepare(`SELECT project, family, command, ok, fail, last_ok FROM commands ${scope} ORDER BY ok DESC`).all(...args),
    sessions: db.prepare(`SELECT id, project, started_at, ended_at, prompts, first_prompt FROM sessions ${scope} ORDER BY started_at DESC LIMIT 500`).all(...args),
    datasets: db.prepare(`SELECT project, name, kind, columns, file FROM datasets ${scope}`).all(...args)
      .map((d) => ({ ...d, columns: d.columns ? JSON.parse(d.columns) : null })),
    edges: db.prepare(`SELECT project, src, dst, file, op FROM edges ${scope}`).all(...args),
  };
}

